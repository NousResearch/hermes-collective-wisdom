#!/usr/bin/env python3
"""Install the repository pre-commit hook without hiding hook conflicts."""

from __future__ import annotations

import argparse
from pathlib import Path
import stat
import subprocess
import sys


MANAGED_MARKER = "File generated by pre-commit"
BACKUP_NAME = "pre-commit.pre-wisdom-backup"


def _run(root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        list(args), cwd=root, check=False, capture_output=True, text=True
    )


def _repository_root() -> Path:
    result = _run(Path.cwd(), "git", "rev-parse", "--show-toplevel")
    if result.returncode:
        raise RuntimeError("run this command inside the repository")
    return Path(result.stdout.strip()).resolve()


def _hook_path(root: Path) -> Path:
    result = _run(root, "git", "rev-parse", "--git-path", "hooks/pre-commit")
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or "cannot locate Git hook directory")
    path = Path(result.stdout.strip())
    return path if path.is_absolute() else root / path


def _refuse_configured_hooks_path(root: Path) -> None:
    result = _run(root, "git", "config", "--get-all", "core.hooksPath")
    if result.returncode not in (0, 1):
        raise RuntimeError(result.stderr.strip() or "cannot inspect core.hooksPath")
    if result.stdout.strip():
        raise RuntimeError(
            "core.hooksPath is configured; refusing before hook inspection"
        )


def install(replace_existing: bool) -> int:
    """Install pre-commit, preserving explicitly replaced conflicting hooks."""
    root = _repository_root()
    if not (root / ".pre-commit-config.yaml").is_file():
        raise RuntimeError("repository has no .pre-commit-config.yaml")
    _refuse_configured_hooks_path(root)
    hook = _hook_path(root)
    backup = hook.with_name(BACKUP_NAME)
    displaced = False
    try:
        hook_stat = hook.lstat()
    except FileNotFoundError:
        hook_stat = None
    if hook_stat is not None:
        if not stat.S_ISREG(hook_stat.st_mode):
            raise RuntimeError(f"refusing non-regular pre-commit hook: {hook}")
        existing = hook.read_text(encoding="utf-8", errors="replace")
        if MANAGED_MARKER not in existing:
            if not replace_existing:
                raise RuntimeError(
                    "existing pre-commit hook is not managed by pre-commit; "
                    "review it, then rerun with --replace-existing to preserve it as "
                    f"{backup.name} without executing it"
                )
            if backup.exists():
                raise RuntimeError(f"refusing to overwrite existing backup: {backup}")
            hook.replace(backup)
            displaced = True

    result = _run(
        root,
        sys.executable,
        "-m",
        "pre_commit",
        "install",
        "--overwrite",
        "--hook-type",
        "pre-commit",
    )
    if result.returncode:
        if displaced:
            if hook.exists():
                hook.unlink()
            backup.replace(hook)
        detail = (result.stderr or result.stdout).strip()
        raise RuntimeError(f"pre-commit installation failed: {detail}")
    print(result.stdout.strip())
    if displaced:
        print(f"preserved previous hook at {backup}")
    return 0


def main() -> int:
    """Parse command-line arguments and report installation errors safely."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--replace-existing",
        action="store_true",
        help="explicitly preserve and replace a conflicting hook",
    )
    args = parser.parse_args()
    try:
        return install(args.replace_existing)
    except (OSError, RuntimeError) as exc:
        print(f"hook installation error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
